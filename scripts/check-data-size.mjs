#!/usr/bin/env node
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { gzipSync } from "node:zlib";

const MAX_FILE_BYTES = 20 * 1024 * 1024;
const MAX_COMPLETE_SEARCH_GZIP_BYTES = 320_000;

function walk(path) {
  return readdirSync(path, { withFileTypes: true }).flatMap((entry) => {
    const child = join(path, entry.name);
    return entry.isDirectory() ? walk(child) : [child];
  });
}

function checkSearchShardBudget(artifactName, label) {
  const artifactPath = join("data", "generated", artifactName);
  if (!existsSync(artifactPath)) {
    return;
  }

  const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
  const shardPaths = artifact.sharded_collection?.shards?.map((shard) => shard.path);
  const paths = Array.isArray(shardPaths) && shardPaths.length
    ? shardPaths.map((path) => join("data", "generated", path))
    : [artifactPath];
  const compressedBytes = Math.max(
    ...paths.map((path) => gzipSync(readFileSync(path), { level: 9 }).byteLength),
  );
  if (compressedBytes > MAX_COMPLETE_SEARCH_GZIP_BYTES) {
    throw new Error(
      `${label} exceeds ${MAX_COMPLETE_SEARCH_GZIP_BYTES} compressed bytes: ${compressedBytes}`,
    );
  }

  console.log(
    `${label} budget check passed: largest shard ${compressedBytes} compressed bytes`,
  );
}

// Raw publisher snapshots are refresh evidence, not static browser payloads.
// The deployment budget applies to the generated runtime artifacts.
const files = walk(join("data", "generated"));
let total = 0;
for (const file of files) {
  const size = statSync(file).size;
  total += size;
  if (size > MAX_FILE_BYTES)
    throw new Error(`${file} exceeds 20 MiB static artifact budget`);
}
checkSearchShardBudget("library-search.json", "Complete library search shard");
checkSearchShardBudget("library-search-index.json", "Library search index shard");
// Combining two existing arrival inputs must not increase their compressed
// byte budget. Measure the actual generated bytes with the same gzip settings.
const compressedBytes = name => gzipSync(readFileSync(join("data", "generated", name)), { level: 9 }).byteLength;
if (compressedBytes("catalog-bootstrap-record.json") > compressedBytes("catalog-bootstrap.json") + compressedBytes("sources.json")) {
  throw new Error("Record bootstrap exceeds the combined catalog/source gzip budget");
}

console.log(
  `Data inventory check passed: ${files.length} files, ${total} bytes total`,
);
